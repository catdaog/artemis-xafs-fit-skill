"""Opt-in real-engine regression: FDMNES_EXE must identify a real executable.

Uses a clearly labelled synthetic target generated by FDMNES, not measured data.
XANES_REAL_TEST_OUT may select an empty directory to retain the evidence.
"""
import copy
import json
import os
from pathlib import Path
import sys
import tempfile
import unittest

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'scripts'))
import fdmnes_runtime as runtime
import xanes_fit as xanes
import numpy as np

ROOT = Path(__file__).resolve().parents[1]


@unittest.skipUnless(os.environ.get('FDMNES_EXE'), 'Set FDMNES_EXE for real engine tests.')
class RealFdmnesTests(unittest.TestCase):
    def test_geometry_refinement_recovers_synthetic_target(self):
        retained = os.environ.get('XANES_REAL_TEST_OUT')
        context = tempfile.TemporaryDirectory() if not retained else None
        folder = Path(retained or context.name)
        folder.mkdir(parents=True, exist_ok=True)
        try:
            config = json.loads((ROOT / 'examples/xanes/fe-n4.json').read_text())
            # Cheap integration test. Production method/convergence is a separate decision.
            config['calculation'].update(method='green', range_eV=[-25, 1, 75])
            config['fit'].update(window_eV=[7109, 7142], offset={'fixed': .03},
                                 additional_starts=[{'fe_n_A': 2.06}])
            config['models'][0]['parameters'][0].update(initial=1.96, bounds=[1.9, 2.12])
            config['models'][0]['provenance'] = 'ILLUSTRATIVE software regression model; synthetic target, not measured data.'
            exe = runtime.resolve_executable()
            calculator = xanes.Calculator(config, exe, folder / 'target-generation')
            target_theory, target_job = calculator.calculate(config['models'][0], {'fe_n_A': 2.03})
            reused = xanes.Calculator(config, exe, folder / 'target-generation')
            reused_spectrum, reused_job = reused.calculate(config['models'][0], {'fe_n_A': 2.03})
            self.assertEqual(reused.launches, 0)
            self.assertEqual(reused_job, target_job)
            np.testing.assert_array_equal(reused_spectrum, target_theory)
            energy = np.arange(7109., 7142.01, .5)
            target = 35 * xanes.aligned_spectrum(target_theory, energy - 7112, .6, .5) + .03
            np.savetxt(folder / 'synthetic_target.csv', np.column_stack([energy, target]), delimiter=',',
                       header='SYNTHETIC FDMNES regression target, not experimental data\nenergy_eV,normalized_mu')
            config['experiment'].update(path='synthetic_target.csv', data_kind='synthetic',
                calibration_basis='SYNTHETIC; E0=7112, generated shift=0.6, not measured calibration.')
            runtime.save_json(folder / 'test_config.json', config)
            result = xanes.execute(folder / 'test_config.json', folder / 'fit', exe)
            fitted = result['results'][0]['parameters']
            self.assertEqual(result['status'], 'review_required')
            self.assertGreater(result['engine_launches'], 3)
            self.assertAlmostEqual(fitted['fe_n_A'], 2.03, delta=.02)
            self.assertAlmostEqual(fitted['shift_eV'], .6, delta=.15)
            self.assertLess(result['results'][0]['rmse'], .002)
            self.assertEqual(result['target_data_kind'], 'synthetic')
            self.assertIn('synthetic_target', (folder / 'fit/FeN4_toy/data_fit.csv').read_text().splitlines()[0])
            # Exercise the finite-difference solver too, without claiming a converged production model.
            fdm = copy.deepcopy(config)
            fdm['calculation'].update(method='fdm', range_eV=[-10, 5, 40])
            fdm_calc = xanes.Calculator(fdm, exe, folder / 'fdm-smoke')
            finite_difference, _ = fdm_calc.calculate(fdm['models'][0], {'fe_n_A': 2.03})
            self.assertGreater(len(finite_difference), 5)
            runtime.save_json(folder / 'regression_evidence.json', {
                'status': 'passed', 'target_type': 'synthetic_not_experimental',
                'truth': {'fe_n_A': 2.03, 'shift_eV': .6, 'amplitude': 35, 'gaussian_sigma_eV': .5},
                'recovered': fitted, 'real_engine_launches': result['engine_launches'],
                'rmse': result['results'][0]['rmse'], 'target_calculation': str(target_job),
                'finite_difference_mode_executed': True})
        finally:
            if context:
                context.cleanup()


if __name__ == '__main__':
    unittest.main()
